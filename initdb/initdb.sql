-- Create two schemas
DROP SCHEMA IF EXISTS foo CASCADE;
CREATE SCHEMA IF NOT EXISTS foo;

DROP SCHEMA IF EXISTS bar CASCADE;
CREATE SCHEMA IF NOT EXISTS bar;

-- Create parent table "valve" in schema "bar"
CREATE TABLE bar.valve (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  valve_name TEXT NOT NULL,
  geom GEOMETRY(Point, 2056) NOT NULL
);

CREATE TABLE foo.vl_control (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description TEXT NOT NULL
);

-- Create child table "control_sheet" in schema "foo"
CREATE TABLE foo.control_sheet (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sheet_name TEXT NOT NULL,
  control_comment TEXT,
  vl_control_id INTEGER REFERENCES foo.vl_control(id),
  valve_id INTEGER NOT NULL REFERENCES bar.valve(id)
);

